package com.dondeloexan.data.local.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.PrimaryKey

@Entity(tableName = "tv_shows")
data class TvShowEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    @ColumnInfo(name = "content_id") val contentId: String? = null,
    @ColumnInfo(name = "tmdb_id") val tmdbId: Int? = null,
    @ColumnInfo(name = "imdb_id") val imdbId: String? = null,
    val title: String,
    val year: Int? = null,
    @ColumnInfo(name = "poster_url") val posterUrl: String? = null,
    @ColumnInfo(name = "rating_tmdb") val ratingTmdb: Float? = null,
    @ColumnInfo(name = "rating_imdb") val ratingImdb: Float? = null,
    @ColumnInfo(name = "certification") val certification: String? = null,
    val status: WatchStatus = WatchStatus.POR_VER,
    val liked: Boolean = false,
    @ColumnInfo(name = "total_episodes") val totalEpisodes: Int? = null,
    @ColumnInfo(name = "streaming_platforms") val streamingPlatforms: String? = null,
    @ColumnInfo(name = "added_at") val addedAt: Long = System.currentTimeMillis(),
    @ColumnInfo(name = "next_episode_air_date") val nextEpisodeAirDate: String? = null,
    @ColumnInfo(name = "next_episode_number") val nextEpisodeNumber: Int? = null,
    @ColumnInfo(name = "next_episode_season") val nextEpisodeSeasonNumber: Int? = null,
    @ColumnInfo(name = "series_status") val seriesStatus: String? = null,
    @ColumnInfo(name = "in_production") val inProduction: Boolean? = null,
    @ColumnInfo(name = "num_seasons") val numberOfSeasons: Int? = null,
    @ColumnInfo(name = "released_episodes") val releasedEpisodes: Int? = null,
    @ColumnInfo(name = "last_watched_at") val lastWatchedAt: Long? = null,
    @ColumnInfo(name = "finished_at") val finishedAt: Long? = null,
    @ColumnInfo(name = "last_refreshed_at") val lastRefreshedAt: Long? = null,
    @ColumnInfo(name = "fa_id") val faId: Int? = null,
    @ColumnInfo(name = "original_title") val originalTitle: String? = null,
    @ColumnInfo(name = "release_date") val releaseDate: String? = null,
    @ColumnInfo(name = "spanish_release_date") val spanishReleaseDate: String? = null,
    @ColumnInfo(name = "digital_release_date") val digitalReleaseDate: String? = null,
    @ColumnInfo(name = "tv_release_date") val tvReleaseDate: String? = null,
    @ColumnInfo(name = "duration_minutes") val durationMinutes: Int? = null,
    @ColumnInfo(name = "rating_rt") val ratingRt: Int? = null,
    @ColumnInfo(name = "rating_metacritic") val ratingMetacritic: Int? = null,
    @ColumnInfo(name = "rating_filmaffinity") val ratingFilmaffinity: Float? = null,
    @ColumnInfo(name = "synopsis") val synopsis: String? = null,
    @ColumnInfo(name = "backdrop_url") val backdropUrl: String? = null,
    @ColumnInfo(name = "directors") val directors: String? = null,
    @ColumnInfo(name = "writers") val writers: String? = null,
    @ColumnInfo(name = "cast_json") val castJson: String? = null,
    @ColumnInfo(name = "music") val music: String? = null,
    @ColumnInfo(name = "cinematography") val cinematography: String? = null,
    @ColumnInfo(name = "production_companies") val productionCompanies: String? = null,
    @ColumnInfo(name = "genres") val genres: String? = null,
    @ColumnInfo(name = "countries") val countries: String? = null,
    @ColumnInfo(name = "external_links") val externalLinks: String? = null
)
